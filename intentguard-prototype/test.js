console.log('\ninjected-content stripping');
check('system-reminder is removed but the human sentence survives', () => {
  const t = cleanText('<system-reminder>\nfile opened\n</system-reminder>\n쿠팡 최종확인으로 표시해줘');
  assert.strictEqual(t, '쿠팡 최종확인으로 표시해줘');
});
check('Caveat preamble is removed', () => {
  const t = cleanText('Caveat: The messages below were generated by the user while running local commands. DO NOT respond to these.\n실제 요구사항');
  assert.strictEqual(t, '실제 요구사항');
});
check('unterminated system-reminder does not swallow nothing', () => {
  assert.strictEqual(cleanText('진짜 메시지\n<system-reminder>truncated'), '진짜 메시지');
});
check('a message that is only injected content becomes empty', () => {
  assert.strictEqual(cleanText('<system-reminder>x</system-reminder>'), '');
});

console.log('\nrecord routing (the core parser claim)');
const R = (o) => routeUserRecord(o, readContent(o.message, null));
check('tool result is not a human message even with role=user', () => {
  assert.strictEqual(R({
    message: { role: 'user', content: [{ type: 'tool_result', tool_use_id: 't', content: 'ls output' }] },
    toolUseResult: { stdout: 'ls output' }, sourceToolAssistantUUID: 'abc', promptId: 'shared',
  }), 'tool_result');
});
check('promptId alone never implies human — tool results inherit it', () => {
  const human = { message: { role: 'user', content: 'hello' }, promptId: 'shared', origin: { kind: 'human' } };
  const tool = { message: { role: 'user', content: [{ type: 'tool_result', content: 'x' }] }, promptId: 'shared' };
  assert.strictEqual(R(human), 'human');
  assert.strictEqual(R(tool), 'tool_result');
});
check('sidechain (sub-agent) prompt is not the operator', () => {
  assert.strictEqual(R({ isSidechain: true, message: { role: 'user', content: 'search the repo' } }), 'sidechain');
});
check('legacy record with no origin field is still human', () => {
  // Older Claude Code builds wrote no origin/promptSource. Requiring them
  // would silently erase the oldest — and most valuable — history.
  assert.strictEqual(R({ message: { role: 'user', content: '월 3회로 제한해줘' } }), 'human');
});

console.log('\ntemporal fold (spec §11) and ambiguity gating (spec §13)');
{
  const { foldEvents, decideFinal } = require('./src/pipeline');
  const ev = (event, timestamp, confidence = 0.9) =>
    ({ candidate_id: 'c_' + timestamp, event, current_statement: '무료 사용자는 월 3회', confidence, timestamp });

  check('§11 worked example: created -> temporarily disabled -> reactivated = ACTIVE', () => {
    const events = [ev('CREATED', '2026-09-01'), ev('TEMPORARILY_DISABLED', '2026-09-05'),
      ev('REACTIVATED', '2026-09-10')];
    const f = foldEvents(events);
    assert.strictEqual(decideFinal(f, events).status, 'ACTIVE');
    assert.deepStrictEqual(f.history.map((h) => h.event),
      ['CREATED', 'TEMPORARILY_DISABLED', 'REACTIVATED']);
  });
  check('a temporary change that never ended stays TEMPORARY, not ACTIVE', () => {
    const events = [ev('CREATED', '2026-09-01'), ev('TEMPORARILY_DISABLED', '2026-09-05')];
    const d = decideFinal(foldEvents(events), events);
    assert.strictEqual(d.status, 'TEMPORARY');
    assert.ok(d.ambiguityReasons.some((r) => /temporary change with no recorded end/.test(r)));
  });
  check('created then rejected is REJECTED, not laundered into AMBIGUOUS', () => {
    // Regressed once: ambiguity detection read the model's raw events, which
    // carry no timestamp, so every event shared the "" bucket and a plain
    // create-then-reject chain was flagged as a timestamp conflict.
    const events = [ev('CREATED', '2026-03-02T11:38:00Z'), ev('REJECTED', '2026-04-11T10:45:00Z')];
    const d = decideFinal(foldEvents(events), events);
    assert.strictEqual(d.status, 'REJECTED', 'reasons: ' + JSON.stringify(d.ambiguityReasons));
    assert.deepStrictEqual(d.ambiguityReasons, []);
  });
  check('genuinely simultaneous contradictory events ARE ambiguous', () => {
    const events = [ev('CREATED', '2026-03-02T11:38:00Z'), ev('REJECTED', '2026-03-02T11:38:00Z')];
    assert.strictEqual(decideFinal(foldEvents(events), events).status, 'AMBIGUOUS');
  });
  check('an UNCLEAR event forces AMBIGUOUS', () => {
    const events = [ev('CREATED', '2026-09-01'), ev('UNCLEAR', '2026-09-05', 0.2)];
    assert.strictEqual(decideFinal(foldEvents(events), events).status, 'AMBIGUOUS');
  });
}

console.log('\ncontext linking (spec §6)');
check('a bare confirmation is linked to the preceding human turn', () => {
  const tl = buildTimeline([
    { uuid: 'm1', route: 'human', rawText: '무료 사용자는 3회로 제한할까?', timestamp: '2026-03-01T00:00:00Z', sessionId: 's', blockTypes: ['string'] },
    { uuid: 'm2', route: 'human', rawText: 'ㅇㅇ', timestamp: '2026-03-01T00:01:00Z', sessionId: 's', blockTypes: ['string'] },
  ]);
  assert.strictEqual(tl[1].message_type, 'HUMAN_CONFIRMATION');
  assert.deepStrictEqual(tl[1].context_message_ids, ['m1']);
});

