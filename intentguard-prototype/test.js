/*
 * Regression test for the Stage 1 parser + filter.
 *
 * STEP 4 of the spec is "fix the filter after a human reviews the samples".
 * That is exactly when a rule change silently breaks a different case, so
 * every case below was found by an actual misclassification, not invented.
 *
 * Run: npm test
 */
const assert = require('assert');
const { execFileSync } = require('child_process');
const fs = require('fs');
const os = require('os');
const path = require('path');

const { cleanText, classify, buildTimeline } = require('./src/filter');
const { routeUserRecord, readContent, parseAll } = require('./src/parse');

let failures = 0;
function check(name, fn) {
  try { fn(); console.log('  ok   ' + name); }
  catch (e) { failures++; console.log('  FAIL ' + name + '\n       ' + e.message); }
}

function cls(text) {
  return classify({ route: 'human', text: cleanText(text) }).type;
}

console.log('\ntext classification');
