const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'ig-test-'));
execFileSync(process.execPath, [path.join(__dirname, 'fixtures/make_fixture.js'), tmp], { stdio: 'pipe' });
const out = path.join(tmp, 'run');
execFileSync(process.execPath, [path.join(__dirname, 'src/analyze.js'), '/home/user/demo-app',
  '--claude-home', tmp, '--out', out], { stdio: 'pipe' });
const data = JSON.parse(fs.readFileSync(path.join(out, 'data/user_messages.json'), 'utf8'));
const debug = JSON.parse(fs.readFileSync(path.join(out, 'data/user_messages.debug.json'), 'utf8'));

check('three sessions merge into one chronological timeline', () => {
  assert.strictEqual(data.meta.sessionCount, 3);
  const ts = data.messages.map((m) => m.timestamp).filter(Boolean);
  const sorted = ts.slice().sort();
  assert.deepStrictEqual(ts, sorted);
});
check('replayed records from a resumed session are de-duplicated', () => {
  assert.ok(debug.diagnostics.duplicateUuids > 0,
    'fixture replays session-2 records into session 3; expected duplicates to be dropped');
  const ids = data.messages.map((m) => m.id);
  assert.strictEqual(new Set(ids).size, ids.length);
});
check('no tool result leaks into the human timeline', () => {
  const leaked = data.messages.filter((m) => m.message_type !== 'TOOL_OR_SYSTEM_CONTENT' && /drwxr-xr-x/.test(m.text));
  assert.strictEqual(leaked.length, 0, 'leaked: ' + JSON.stringify(leaked.slice(0, 2)));
});
check('the temporal chain (limit -> lifted -> restored -> superseded) survives filtering', () => {
  const kept = data.messages.filter((m) => m.message_type === 'HUMAN_INTENT' || m.message_type === 'HUMAN_CORRECTION')
    .map((m) => m.text).join('\n');
  for (const needle of ['월 3회만', '제한 풀어', '다시 월 3회로', '5회로 하자', '빼자', '카카오 로그인']) {
    assert.ok(kept.includes(needle), 'lost from intent-bearing set: ' + needle);
  }
});
check('nothing is classified UNKNOWN in the fixture', () => {
  const unk = data.messages.filter((m) => m.message_type === 'UNKNOWN');
  assert.strictEqual(unk.length, 0, 'unknown: ' + JSON.stringify(unk.map((m) => m.text)));
});
check('STEP 3 artifacts are all written', () => {
  for (const f of ['output/message_filter_samples.md', 'output/message_filter_report.md',
    'output/parse_diagnostics.md', 'data/user_messages.json']) {
    assert.ok(fs.existsSync(path.join(out, f)), 'missing ' + f);
  }
});
