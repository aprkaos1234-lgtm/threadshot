const CORRECTION = [
  /아니(?![ا-힣])/, /아니고/, /아니라/, /말고/, /대신/, /다시\s*(해|돌려|바꿔)/,
  /취소/, /되돌려/, /원래대로/, /롤백/, /빼(줘|자|고)?\b/, /지워/, /삭제해/, /없애/,
  /하지\s*마/, /하지말/, /그거\s*말고/, /방금\s*것?\s*(취소|빼)/, /잘못/,
  /빼[자줘고는]/, /빼\s*$/, /제외/, /없애/, /중단/, /철회/,
  /\brevert\b/i, /\bundo\b/i, /\brollback\b/i, /\bnot that\b/i, /\binstead\b/i,
  /\bremove\b/i, /\bdrop\b/i, /\bcancel\b/i, /\bscrap\b/i, /\bnever ?mind\b/i,
  /\bactually,?\s/i, /\bno,\s/i, /\bwrong\b/i,
];

const REQUIREMENT = [
  /해줘/, /해주세요/, /만들어/, /추가/, /구현/, /넣어/, /바꿔/, /변경/, /수정/,
  /지원/, /제한/, /적용/, /설정해/, /해야/, /하게\s*해/, /되게\s*해/, /필요해/, /원해/,
  /보여줘/, /표시/, /저장/, /삭제되게/, /막아/, /허용/, /기능/, /만들자/, /하자/,
  /\badd\b/i, /\bimplement\b/i, /\bcreate\b/i, /\bmake\b/i, /\bchange\b/i, /\bsupport\b/i,
  /\ballow\b/i, /\blimit\b/i, /\brestrict\b/i, /\bshould\b/i, /\bmust\b/i, /\bneed(s)? to\b/i,
  /\bi want\b/i, /\bplease\b/i, /\benable\b/i, /\bdisable\b/i, /\bfix\b/i, /\bshow\b/i,
];

const QUESTION = [
  /\?\s*$/, /어때/, /어떻게/, /뭐야/, /무엇/, /인가요/, /있나요/, /될까/, /할까/, /가능해/,
  /맞아\?/, /왜/, /\bwhy\b/i, /\bwhat\b/i, /\bhow\b/i, /\bcan you\b/i, /\bis it\b/i,
  /\bshould we\b/i, /\bdoes\b/i,
  // Tag questions ("…되지", "…있지") are frequently typed with no question mark
  // at all, and Korean lets a word trail the verb ("연결되있지 이컴퓨터").
  // Checked after the requirement rules, so "…하게 해줘" still wins.
  /[가-힣]지\s*[?？]?(\s+\S{1,12})?\s*$/m,
];

// Korean marks a request by verb ending, not by a keyword. A keyword list
// alone missed "…기준으로 써줘" and "…자동 갱신하게", which are plainly
// requirements. These match the ending of any line.
const KO_REQUEST_ENDING = [
  // "줘" need not end the line: "완성해서 줘, 일단 프로토타입" is still a request.
  /[가-힣]\s*줘(\s*[,.!~…]|\s*$)/m,   // …해줘 / …써줘 / …넣어줘
  /[가-힣]\s*주세요(\s*[,.!~…]|\s*$)/m,
  /[가-힣]게\s*[.!~…]*$/m,            // …되게 / …갱신하게
  /[가-힣]자\s*[.!~…]*$/m,            // …하자 / …바꾸자
  /[가-힣]해\s*[.!~…]*$/m,            // …제한해
  /[가-힣]도록\s*[.!~…]*$/m,
];

// Soft rejections: "아직은 됐어" declines a proposal, but "됐어" can also mean
// "it works now". Genuinely ambiguous at Stage 1 — flagged with low confidence
// so Stage 2 (and the human review in STEP 3) can see it.
const SOFT_REJECTION = [
  /됐어/, /됐다/, /됐습니다/, /필요\s*없/, /안\s*해도\s*(돼|됨|될)/,
  /보류/, /나중에\s*(하|보)/, /일단\s*(넘어가|두)/, /스킵/, /\bskip\b/i,
];

function matches(t, list) {
  return list.some((re) => re.test(t));
}

// ---------------------------------------------------------------------------
// Classification
// ---------------------------------------------------------------------------

const SHORT_LIMIT = 14;

function classify(entry) {
  const reasons = [];

  if (entry.route === 'tool_result') {
    return { type: 'TOOL_OR_SYSTEM_CONTENT', confidence: 0.99, reasons: ['tool_result record'] };
  }
  if (entry.route === 'sidechain') {
    return { type: 'TOOL_OR_SYSTEM_CONTENT', confidence: 0.95, reasons: ['isSidechain=true (sub-agent)'] };
  }
  if (entry.route === 'empty') {
    return { type: 'TOOL_OR_SYSTEM_CONTENT', confidence: 0.8, reasons: ['no text content'] };
  }

  const t = entry.text;
  if (!t) {
    return { type: 'TOOL_OR_SYSTEM_CONTENT', confidence: 0.85, reasons: ['empty after stripping injected blocks'] };
  }
  for (const re of SYSTEM_WHOLE) {
    if (re.test(t)) {
      return { type: 'TOOL_OR_SYSTEM_CONTENT', confidence: 0.9, reasons: ['system/slash/wake envelope: ' + re.source.slice(0, 40)] };
    }
  }

  if (looksLikeErrorLog(t)) {
    return { type: 'ERROR_LOG', confidence: 0.85, reasons: ['stack trace / error output shape'] };
  }
  if (looksLikePaste(t)) {
    return { type: 'PASTED_CONTENT', confidence: 0.75, reasons: ['bulk code/terminal paste shape'] };
  }

  const compact = t.replace(/\s+/g, ' ').trim();
  if (compact.length <= SHORT_LIMIT) {
    if (inVocab(compact, CONFIRM)) {
      return { type: 'HUMAN_CONFIRMATION', confidence: 0.8, reasons: ['short affirmative — must be read against prior context'] };
    }
    if (inVocab(compact, CONTINUE)) {
      return { type: 'LOW_INFORMATION', confidence: 0.85, reasons: ['continuation / filler'] };
    }
    if (matches(compact, CORRECTION)) {
      return { type: 'HUMAN_CORRECTION', confidence: 0.6, reasons: ['short correction marker'] };
    }
    if (compact.length <= 4) {
      return { type: 'LOW_INFORMATION', confidence: 0.7, reasons: ['too short to carry intent'] };
    }
    reasons.push('short message, no vocabulary hit');
  }

  const isCorrection = matches(t, CORRECTION);
  const isRequirement = matches(t, REQUIREMENT) || matches(t, KO_REQUEST_ENDING);
  const isQuestion = matches(t, QUESTION);

  if (!isCorrection && matches(t, SOFT_REJECTION)) {
    reasons.push('soft rejection — but "됐어" can also mean "it works now"; needs context');
    return { type: 'HUMAN_CORRECTION', confidence: 0.45, reasons };
  }
  if (isCorrection) {
    reasons.push('correction marker');
    // A correction that also states a new requirement is still a correction:
    // temporal reconciliation cares about the supersede relationship.
    return { type: 'HUMAN_CORRECTION', confidence: isRequirement ? 0.8 : 0.65, reasons };
  }
  // A short, explicitly question-marked line ("팀 기능도 나중에 만들까?") is a
  // proposal, not a standing requirement, even though it contains requirement
  // vocabulary. Stage 2 is where IDEA vs REQUIREMENT gets decided.
  const isProposal = isQuestion && /\?/.test(t) && compact.length < 40;
  if (isRequirement && !isProposal) {
    reasons.push('requirement/imperative marker');
    if (isQuestion) reasons.push('also question-shaped — Stage 2 must split REQUIREMENT vs IDEA');
    return { type: 'HUMAN_INTENT', confidence: isQuestion ? 0.55 : 0.8, reasons };
  }
  if (isQuestion) {
    reasons.push('question shape — not an active requirement on its own');
    return { type: 'HUMAN_CONTEXT', confidence: 0.7, reasons };
  }
  if (compact.length >= 40) {
    reasons.push('substantial prose without imperative marker');
    return { type: 'HUMAN_CONTEXT', confidence: 0.5, reasons };
  }
  return { type: 'UNKNOWN', confidence: 0.3, reasons: reasons.concat('no rule matched') };
}

const HUMAN_TYPES = new Set([
  'HUMAN_INTENT', 'HUMAN_CONTEXT', 'HUMAN_CONFIRMATION', 'HUMAN_CORRECTION',
  'LOW_INFORMATION', 'UNKNOWN',
]);
const INTENT_BEARING = new Set(['HUMAN_INTENT', 'HUMAN_CORRECTION']);
const NOISE_TYPES = new Set(['TOOL_OR_SYSTEM_CONTENT', 'PASTED_CONTENT', 'ERROR_LOG']);

/**
 * Build the normalized timeline (spec §8), linking low-information and
 * confirmation messages back to the human messages that give them meaning.
 */
function buildTimeline(userEntries) {
  const out = [];
  const priorHuman = [];
  for (const e of userEntries) {
    const text = e.route === 'human' ? cleanText(e.rawText) : '';
    const withText = Object.assign({}, e, { text });
    const c = classify(withText);
    const rec = {
      id: e.uuid,
      session_id: e.sessionId,
      timestamp: e.timestamp,
      text,
      message_type: c.type,
      context_message_ids: [],
      confidence: c.confidence,
      // debug fields, not part of the §8 contract
      _reasons: c.reasons,
      _route: e.route,
      _origin_kind: e.originKind,
      _prompt_source: e.promptSource,
      _raw_len: (e.rawText || '').length,
      _clean_len: text.length,
      _block_types: e.blockTypes,
    };
    if (c.type === 'HUMAN_CONFIRMATION' || c.type === 'LOW_INFORMATION' || c.type === 'UNKNOWN') {
      rec.context_message_ids = priorHuman.slice(-2).map((p) => p.id);
    }
    if (HUMAN_TYPES.has(c.type) && text) priorHuman.push(rec);
    out.push(rec);
  }
  return out;
}

function tally(timeline) {
  const byType = {};
  for (const r of timeline) byType[r.message_type] = (byType[r.message_type] || 0) + 1;
  const human = timeline.filter((r) => HUMAN_TYPES.has(r.message_type) && r.text);
  return {
    rawUserRole: timeline.length,
    humanMessages: human.length,
    intentBearing: timeline.filter((r) => INTENT_BEARING.has(r.message_type)).length,
    lowInformation: (byType.LOW_INFORMATION || 0) + (byType.HUMAN_CONFIRMATION || 0) + (byType.HUMAN_CONTEXT || 0),
    noise: timeline.filter((r) => NOISE_TYPES.has(r.message_type)).length,
    unknown: byType.UNKNOWN || 0,
    byType,
  };
}

module.exports = {
  cleanText, classify, buildTimeline, tally,
  HUMAN_TYPES, INTENT_BEARING, NOISE_TYPES,
  looksLikeErrorLog, looksLikePaste,
};
