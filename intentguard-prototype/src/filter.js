'use strict';

/*
 * Stage 1 — Raw Human Message Filtering (spec §6).
 *
 * Deterministic, zero LLM calls, zero cost. This runs BEFORE any money is
 * spent, because the whole point of STEP 3 is to let a human look at the
 * filter's output before an expensive pipeline is built on top of it.
 *
 * Buckets: HUMAN_INTENT, HUMAN_CONTEXT, HUMAN_CONFIRMATION, HUMAN_CORRECTION,
 *          PASTED_CONTENT, ERROR_LOG, TOOL_OR_SYSTEM_CONTENT,
 *          LOW_INFORMATION, UNKNOWN
 */

// ---------------------------------------------------------------------------
// Text cleaning: strip content the harness injects into human-authored turns.
// ---------------------------------------------------------------------------

const STRIP_BLOCKS = [
  /<system-reminder>[\s\S]*?<\/system-reminder>/g,
  /<local-command-stdout>[\s\S]*?<\/local-command-stdout>/g,
  /<local-command-stderr>[\s\S]*?<\/local-command-stderr>/g,
  /<command-message>[\s\S]*?<\/command-message>/g,
  /<command-args>[\s\S]*?<\/command-args>/g,
  /<untrusted_external_data[\s\S]*?<\/untrusted_external_data>/g,
  /<function_results>[\s\S]*?<\/function_results>/g,
  /<user-memory-input>[\s\S]*?<\/user-memory-input>/g,
  // unterminated variants (truncated transcripts)
  /<system-reminder>[\s\S]*$/g,
];

const CAVEAT = /^Caveat:\s*The messages below were generated by the user while running[^\n]*\n?/;

// Whole-message markers: if present, the record is machinery, not intent.
const SYSTEM_WHOLE = [
  /^<command-name>/,
  /^\/[A-Za-z0-9_:-]+\s*$/,          // bare slash command after expansion
  /^<wake\s+reason=/,
  /^<event\s+source=/,
  /^<webhook-payload/,
  /^<local-command/,
  /^<ide_selection/,
  /^<bash-input>/,
  /^\[Request interrupted by user/,
  /^API Error/,
  /^\s*<\/?[a-z-]+>\s*$/i,
];

function cleanText(raw) {
  let t = String(raw == null ? '' : raw);
  t = t.replace(CAVEAT, '');
  for (const re of STRIP_BLOCKS) t = t.replace(re, '');
  // slash-command expansion: keep the command name so it can be reported,
  // drop the machine-generated body. The captured name may or may not already
  // carry a leading slash, so normalise to exactly one.
  t = t.replace(/<command-name>\s*\/?([^<]*)<\/command-name>/g, '/$1');
  t = t.replace(/\r/g, '');
  return t.trim();
}

// ---------------------------------------------------------------------------
// Shape detectors
// ---------------------------------------------------------------------------

const ERROR_PATTERNS = [
  /Traceback \(most recent call last\)/,
  /^\s+at [\w$.<>]+ \(.*:\d+:\d+\)/m,
  /^\s*File ".*", line \d+/m,
  /\bnpm ERR!/,
  /\bECONNREFUSED\b|\bENOENT\b|\bEADDRINUSE\b/,
  /^[A-Za-z.]*(Error|Exception):\s/m,
  /error TS\d{4}:/,
  /panic: /,
];

const CODEY = /[{};=<>()[\]]|=>|::|\bfunction\b|\bconst \b|\bimport \b|\bdef \b|\bclass \b|^\s{2,}\S/;

function looksLikeErrorLog(t) {
  const hits = ERROR_PATTERNS.filter((re) => re.test(t)).length;
  if (hits >= 2) return true;
  return hits >= 1 && (t.length > 200 || t.split('\n').length >= 4);
}

function looksLikePaste(t) {
  const lines = t.split('\n');
  if (lines.length >= 8) {
    const codey = lines.filter((l) => l.trim() && CODEY.test(l)).length;
    if (codey / lines.length >= 0.5) return true;
  }
  // a message that is mostly a fenced block
  const fenced = (t.match(/```[\s\S]*?```/g) || []).join('');
  if (fenced.length > 0 && fenced.length / t.length > 0.7 && t.length > 400) return true;
  // very long with almost no sentence structure
  if (t.length > 3000 && lines.length > 40) {
    const codey = lines.filter((l) => l.trim() && CODEY.test(l)).length;
    if (codey / lines.length >= 0.35) return true;
  }
  return false;
}

