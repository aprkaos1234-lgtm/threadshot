const CONFIRM = [
  'ㅇㅇ', 'ㅇㅋ', 'ㄱㄱ', 'ㅇ', 'ok', 'okay', 'oki', 'k', 'yes', 'y', 'yep', 'yeah', 'sure',
  '네', '넵', '응', '어', '그래', '그래요', '좋아', '좋아요', '좋습니다', '맞아', '맞아요',
  '해줘', '해', '진행', '진행해', '고고', 'ㄱ', 'do it', 'go ahead', 'go', 'approved', 'lgtm',
  '동의', '승인', '오케이', '오키', '그렇게', '그렇게 해', '그거로', '맞습니다',
];

const CONTINUE = [
  '계속', '계속해', '계속해줘', 'continue', 'go on', 'next', '다음', '더', 'more',
  '...', '.', '??', '?', 'ㅁ', 'ㄴ', 'hmm', '음', '아', 'ㅎㅎ', 'ㅋㅋ', 'ㅋ', 'thanks', '고마워',
  '감사', '감사합니다', 'ty', 'nice', 'good', '굿', '수고', '수고했어',
];

function normShort(t) {
  return t.toLowerCase().replace(/[\s!.~^]+/g, ' ').trim();
}

function inVocab(t, vocab) {
  const n = normShort(t);
  return vocab.includes(n) || vocab.includes(n.replace(/\s/g, ''));
}

